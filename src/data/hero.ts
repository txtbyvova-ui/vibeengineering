import type { Link } from "@/types";

/**
 * Кусок заголовка. `accent` — акцентный цвет палитры (`text-accent`),
 * `break` — перенос строки перед куском. Курсива в описании больше нет:
 * его в наборе шрифтов не существует, и разметка им не красит.
 */
export interface HeadlinePart {
  text: string;
  accent?: boolean;
  break?: boolean;
}

/**
 * Первый экран отвечает на два вопроса за пять секунд: ЧТО делаем и ДЛЯ КОГО.
 * Поэтому заголовок называет результат, а не биографию бюро, а подзаголовок —
 * прямым текстом перечисляет услуги, аудиторию и срок.
 *
 * Прежний заголовок «Мы строили мосты, порталы и ивенты. Теперь строим ваш
 * digital.» рассказывал про нас; посетитель из рекламы узнавал, чем мы
 * занимались, но не что получит он. История про мосты никуда не делась —
 * она в USP и в цитате Романа в Team, где ей и место.
 */
export const hero = {
  /**
   * Первая строка страницы. Была английской — её читал и не понимал никто.
   * Без ◆ в отличие от надстрочников остальных секций: здесь маркер уже есть,
   * это пульсирующая точка слева, и два значка подряд читались как опечатка.
   */
  microLabel: "Инженерное бюро · Москва",
  /**
   * ⚠️ Разбивка на строки задана здесь ЯВНО, и это про CLS, а не про вкус.
   * Одной строкой «которые приносят деньги» упиралась в границу переноса
   * ровно на ходовых ноутбучных ширинах: на 960 px — две строки, на 1000 px —
   * одна. Подгрузка шрифта на ~1.5 с меняет ширину текста на пару процентов,
   * строка перекидывалась обратно, высота h1 прыгала на 60 px вместе со всем
   * блоком — замеренный CLS на 1024 px был **0.16** при пороге Google 0.1.
   *
   * Теперь самая длинная строка — «которые приносят», 16 знаков: до границы
   * переноса ей далеко на любой ширине, и счёт строк от шрифта не зависит.
   * Меняя текст, проверять не только как он смотрится, но и что число строк
   * не пляшет между 320 и 1920 px.
   */
  headline: [
    { text: "Сайты и боты," },
    { text: "которые", break: true },
    { text: "приносят" },
    { text: "деньги", accent: true, break: true },
  ] satisfies HeadlinePart[],
  lead:
    "Сайты, Telegram-боты, веб-приложения и AI — для малого и среднего бизнеса. " +
    "Считаем нагрузку до старта, первый рабочий результат отдаём через 48 часов.",
  /**
   * Ведёт прямо в Telegram, а не якорем на секцию контактов: требование
   * «контакт доступен в hero-зоне», а не «до контакта можно долистать».
   * Внешний адрес — Hero сам проставит `target`/`rel` по протоколу.
   */
  cta: {
    label: "Обсудить проект",
    href: "https://t.me/vovaegorovv",
  } satisfies Link,
  ctaNote: "Ответим за 2 часа · Telegram",
} as const;
