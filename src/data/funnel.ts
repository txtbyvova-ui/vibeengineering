/**
 * Воронка конверсии — геометрия и ручки. Всё, что стоит крутить, здесь.
 *
 * Профиль `funnelRadius` — общий для 3D-сцены и статичного SVG-фолбэка:
 * это буквально одна и та же воронка, просто нарисованная двумя способами.
 * Если правите силуэт — правите оба вида сразу, разъехаться они не могут.
 *
 * Метрика успеха здесь одна: читается ли «лиды → воронка → касса» без подписи.
 * Поэтому силуэт не конус, а именно воронка — чаша плюс носик.
 */
export const FUNNEL = {
  // ── силуэт ────────────────────────────────────────────────────────────────
  /** Высота от устья до кассы, в юнитах сцены. */
  height: 3.5,
  /** Радиус устья: сюда падают лиды. */
  radiusTop: 1.6,
  /** Радиус носика. Меньше 0.1 — частицы сливаются в одну нитку и поток пропадает. */
  radiusNeck: 0.18,
  /** Доля высоты, на которой чаша переходит в носик. Без носика силуэт — конус. */
  neckAt: 0.74,
  /**
   * Кривизна чаши. 1.0 — прямой конус (читается как «рупор»),
   * 1.75 — вогнутая стенка, узнаваемая воронка. Выше 2.4 — «рюмка».
   */
  taperPower: 1.75,

  // ── каркас ────────────────────────────────────────────────────────────────
  /** Колец по высоте. Распределены с уплотнением к носику — там силуэт круче. */
  rings: 16,
  /** Сегментов в кольце. 72 — окружность гладкая, 24 — виден многоугольник. */
  ringSegments: 72,
  /** Каждое N-е кольцо силовое: ярче. Без иерархии каркас читается как «сетка». */
  majorRingEvery: 4,
  /** Направляющих (меридианов) — они же «трубы», по ним читается направление вниз. */
  meridians: 18,
  majorMeridianEvery: 6,
  /** Уплотнение колец к носику: 1 — равномерно, 1.7 — заметно гуще внизу. */
  ringBias: 1.7,

  // ── поток ─────────────────────────────────────────────────────────────────
  /**
   * Частиц в потоке. 900 при аддитивном блендинге сливались в «песчаную бурю»
   * и забивали каркас — читалось облако, а не поток по стенке воронки.
   */
  particles: 720,
  /** Откуда сыплются: t < 0 — отвесное падение над устьем. */
  spawnAt: -0.22,
  /** Базовая скорость, доля пути в секунду. */
  speed: 0.26,
  /** Разброс скоростей — без него поток идёт «расчёской». */
  speedJitter: 0.5,
  /**
   * Ускорение к носику: v · (1 + accel · t²). Вода в воронке разгоняется,
   * и именно это читается как «сужение», а не просто сходящиеся точки.
   */
  accel: 2.2,
  /** Закрутка. Момент импульса растёт при сужении — вихрь у носика сам собой. */
  swirl: 0.55,
  /** Толщина потока поперёк стенки: 0 — частицы строго по каркасу, мертво. */
  wallJitter: 0.16,
  /** Диаметр точки в юнитах сцены (не в пикселях): дальние сами мельчают. */
  pointSize: 0.046,
  /** Разброс размеров — поток перестаёт выглядеть штампованным. */
  pointSizeJitter: 0.45,

  // ── касса ─────────────────────────────────────────────────────────────────
  /** На сколько ниже носика стоит узел накопления. */
  registerDrop: 0.34,
  registerRadius: 0.3,
  /** Вклад одной прибывшей частицы во вспышку. */
  flashPerArrival: 0.055,
  /** Постоянная затухания вспышки, с. Больше — касса «горит» дольше. */
  flashTauS: 0.42,
  /** Потолок вспышки: без него плотный поток выжигает кассу в белое пятно. */
  flashMax: 1,

  // ── камера ────────────────────────────────────────────────────────────────
  camera: {
    /**
     * z подобран так, чтобы вся воронка ВМЕСТЕ с кассой влезала в кадр:
     * видимая высота = 2·z·tan(fov/2) должна быть > height + registerDrop.
     * При 5.2 это давало 3.58 против нужных 3.84 — устье срезало сверху,
     * а касса уходила за нижнюю кромку.
     */
    position: [0, 0.15, 6.9] as const,
    lookAt: [0, -0.12, 0] as const,
    fov: 38,
    /** Амплитуда параллакса по осям, юниты. */
    parallax: [0.42, 0.26] as const,
    /** Постоянная демпфирования, мс. Камера тяжёлая: 90 — «указка», 600 — кисель. */
    tauMs: 340,
  },

  // ── цвет (blueprint: холодный каркас, тёплый поток) ───────────────────────
  color: {
    /** Каркас. Синий, а не серый: сразу читается «чертёж», а не «проволока». */
    frame: "#2F6DA8",
    frameOpacity: 0.26,
    frameMajor: "#5AA0E0",
    frameMajorOpacity: 0.5,
    /** Поток и касса — брендовый акцент. */
    flow: "#FF4F00",
    register: "#FF7A3D",
  },

  // ── бюджет кадра ──────────────────────────────────────────────────────────
  /** Потолок devicePixelRatio: заливка растёт как dpr². */
  dprCap: 2,
  /**
   * Потолок кадров. 60 при 60 Гц — кадр в кадр; 30 — ровно каждый второй.
   * Промежуточные значения дают рваный пейсинг и выглядят хуже честных 30.
   */
  fpsCap: 60,
  /** Ниже этого fps дольше badWindows окон — роняем dpr, потом гасим сцену. */
  minFps: 24,
} as const;

/**
 * Радиус воронки на глубине `t` (0 — устье, 1 — носик).
 * При t < 0 частица ещё падает над устьем и радиус не меняется.
 */
export function funnelRadius(t: number): number {
  if (t <= 0) return FUNNEL.radiusTop;
  if (t >= FUNNEL.neckAt) return FUNNEL.radiusNeck;
  const u = t / FUNNEL.neckAt;
  return (
    FUNNEL.radiusNeck + (FUNNEL.radiusTop - FUNNEL.radiusNeck) * Math.pow(1 - u, FUNNEL.taperPower)
  );
}

/** Высота точки воронки на глубине `t`, в юнитах сцены. */
export function funnelY(t: number): number {
  return FUNNEL.height * (0.5 - t);
}

/** Глубины колец: с уплотнением к носику, где силуэт меняется быстрее всего. */
export function ringDepths(): number[] {
  const out: number[] = [];
  for (let i = 0; i < FUNNEL.rings; i++) {
    const u = i / (FUNNEL.rings - 1);
    out.push(Math.pow(u, FUNNEL.ringBias));
  }
  return out;
}
